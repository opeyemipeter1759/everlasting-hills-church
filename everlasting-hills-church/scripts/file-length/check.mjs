/**
 * Fails when a frontend source file is longer than MAX_LINES.
 *
 * Files that were already too long when this rule arrived are listed in
 * baseline.json with their length at the time. They may only shrink: a
 * listed file that grows fails, and one that drops to MAX_LINES or under
 * should be taken off the list (`--update` does that). New files get no
 * allowance. When the list is empty the rule holds for every file.
 *
 *   node scripts/file-length/check.mjs            check (pre-commit, pre-push, CI)
 *   node scripts/file-length/check.mjs --update   drop fixed files, lower shrunk ones
 *
 * The baseline only ever shrinks: --update never adds a file or raises a limit.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const MAX_LINES = 150;

const HERE = dirname(fileURLToPath(import.meta.url));
export const ROOT = join(HERE, "..", "..");
const BASELINE_PATH = join(HERE, "baseline.json");

const EXTENSIONS = /\.(tsx?|jsx?|mjs|cjs|css)$/;
/** Folders that are not hand-written source: dependencies, build output, generated code. */
const SKIP_DIRS = new Set(["node_modules", ".next", "public", "coverage", ".turbo", ".vercel", "out"]);
/** Generated files, regenerated by tools rather than edited. */
const SKIP_FILES = new Set(["next-env.d.ts", "lib/api/generated/schema.d.ts"]);

function toPosix(path) {
  return path.split(sep).join("/");
}

function* walk(dir) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) yield* walk(full);
    else if (EXTENSIONS.test(entry)) yield full;
  }
}

export function countLines(text) {
  if (!text) return 0;
  const lines = text.split(/\r?\n/);
  return text.endsWith("\n") ? lines.length - 1 : lines.length;
}

/** Every checked file and its length, keyed by its path from the frontend root. */
export function measure(root = ROOT) {
  const sizes = {};
  for (const file of walk(root)) {
    const path = toPosix(relative(root, file));
    if (SKIP_FILES.has(path) || path.startsWith("lib/api/generated/")) continue;
    sizes[path] = countLines(readFileSync(file, "utf8"));
  }
  return sizes;
}

export function readBaseline() {
  return JSON.parse(readFileSync(BASELINE_PATH, "utf8")).files;
}

/** Compares lengths with the baseline. Pure, so tests can feed it anything. */
export function check(sizes, baseline, max = MAX_LINES) {
  const tooLong = [];
  const grew = [];
  const fixed = [];
  for (const [path, lines] of Object.entries(sizes)) {
    const allowed = baseline[path];
    if (allowed === undefined) {
      if (lines > max) tooLong.push({ path, lines });
    } else if (lines <= max) {
      fixed.push({ path, lines });
    } else if (lines > allowed) {
      grew.push({ path, lines, allowed });
    }
  }
  const gone = Object.keys(baseline).filter((path) => !(path in sizes));
  return { tooLong, grew, fixed, gone, ok: tooLong.length === 0 && grew.length === 0 };
}

/** The baseline after fixes: entries removed or lowered, never added or raised. */
export function shrinkBaseline(sizes, baseline, max = MAX_LINES) {
  const next = {};
  for (const [path, allowed] of Object.entries(baseline)) {
    const lines = sizes[path];
    if (lines === undefined || lines <= max) continue;
    next[path] = Math.min(allowed, lines);
  }
  return next;
}

function report(result) {
  const out = [];
  for (const { path, lines } of result.tooLong) out.push(`  ✗ ${path}: ${lines} lines (max ${MAX_LINES})`);
  for (const { path, lines, allowed } of result.grew) {
    out.push(`  ✗ ${path}: grew to ${lines} lines (was ${allowed}; it may only shrink until it is ${MAX_LINES} or less)`);
  }
  return out.join("\n");
}

function main() {
  const sizes = measure();
  const baseline = readBaseline();

  if (process.argv.includes("--update")) {
    const next = shrinkBaseline(sizes, baseline);
    writeFileSync(BASELINE_PATH, `${JSON.stringify({ max: MAX_LINES, files: next }, null, 2)}\n`);
    console.log(`File-length baseline: ${Object.keys(baseline).length} → ${Object.keys(next).length} files still over ${MAX_LINES} lines.`);
    return;
  }

  const result = check(sizes, baseline);
  if (!result.ok) {
    console.error(`\nFile length check failed: frontend files must be ${MAX_LINES} lines or less.\n`);
    console.error(report(result));
    console.error("\nSplit the file into smaller modules (components, hooks, helpers) and try again.\n");
    process.exit(1);
  }
  const stale = result.fixed.length + result.gone.length;
  if (stale) {
    console.log(`File length: ${stale} file(s) on the baseline are now within ${MAX_LINES} lines or gone.`);
    console.log("Run `npm run check:file-length -- --update` to lock that in.");
  }
  console.log(`File length OK (${Object.keys(baseline).length - stale} older files still to split).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
